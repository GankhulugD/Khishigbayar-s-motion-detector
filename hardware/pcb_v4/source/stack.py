blk(1, 4.8, 6.5, 6.3, "#f08c00", "C1\nхэвтээ", fs=8)
blk(0, 11.4, 36, 1.0, "#2b8a3e", "Самбар B (2 давхарга)", fs=8)
blk(22, 12.4, 12, 8.5, "#adb5bd", "", tc="#111", fs=8)
blk(0.2, 16.9, 17, 4.0, "#1c7ed6", "TP4056 (A доод, наана)", fs=8)
blk(17.5, 14.4, 18, 6.5, "#212529", "ESP32-S3-Zero\n(A доод, header дээр)", fs=8)
blk(0, 20.9, 36, 1.0, "#2b8a3e", "Самбар A (2 давхарга)", fs=8)
blk(0.5, 21.9, 27.3, 2.5, "#adb5bd", "OLED header", tc="#111", fs=8)
blk(0.5, 24.4, 27.3, 3.6, "#0b0b12", "OLED 0.96\" дэлгэц", fs=9)
ax.annotate("J4 самбар хоорондын холбогч\n(эм 8.5 мм + эрэгтэйн хуванцар 2.5 мм)\nM2 тулгуур ≈ 11 мм", xy=(34, 13.5), xytext=(38, 12.5), fontsize=9, arrowprops=dict(arrowstyle="->"), va="center")
ax.text(18, -5.2, "USB-C: TP4056 (цэнэглэх) ба ESP32-S3-Zero (програмчлах) — хоёулаа доод ирмэгт", ha="center", fontsize=9, color="#555")
ax.annotate("", xy=(-3, 0), xytext=(-3, 28), arrowprops=dict(arrowstyle="<->"))
ax.text(-3.6, 14, "≈ 28 мм", rotation=90, ha="right", va="center", fontsize=10)
