import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
fig, ax = plt.subplots(figsize=(11, 6.2), dpi=170)
def blk(x, y, w, h, fc, txt, tc="white", fs=10):
    ax.add_patch(plt.Rectangle((x, y), w, h, fc=fc, ec="#333", lw=0.8))
    ax.text(x + w / 2, y + h / 2, txt, ha="center", va="center", color=tc, fontsize=fs, fontweight="bold")
# доороос дээш (мм)
blk(0, 0, 36, 4.5, "#8e8e93", "LiPo батерей 3.7V (жишээ: 503035, ~500 mAh)")
